#!/usr/bin/env node
/**
 * InformedDiet Branding Automation Script
 * Reads branding/brand.json and branding/*.png, checks WCAG contrast,
 * updates mobile/assets/*, mobile/app.json, and mobile/src/config/brand.ts.
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const brandingDir = path.join(rootDir, 'branding');
const mobileDir = path.join(rootDir, 'mobile');
const assetsDir = path.join(mobileDir, 'assets');
const configDir = path.join(mobileDir, 'src', 'config');

function hexToRgb(hex) {
  const clean = hex.replace('#', '');
  const num = parseInt(clean, 16);
  return { r: (num >> 16) & 255, g: (num >> 8) & 255, b: num & 255 };
}

function relativeLuminance({ r, g, b }) {
  const [rs, gs, bs] = [r, g, b].map((c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * rs + 0.7152 * gs + 0.0722 * bs;
}

function contrastRatio(hex1, hex2) {
  const l1 = relativeLuminance(hexToRgb(hex1));
  const l2 = relativeLuminance(hexToRgb(hex2));
  const lighter = Math.max(l1, l2);
  const darker = Math.min(l1, l2);
  return (lighter + 0.05) / (darker + 0.05);
}

function run() {
  const brandPath = path.join(brandingDir, 'brand.json');
  if (!fs.existsSync(brandPath)) {
    console.error('ERROR: branding/brand.json not found.');
    process.exit(1);
  }

  const brand = JSON.parse(fs.readFileSync(brandPath, 'utf-8'));

  // Accessibility contrast check (white text on primaryColor)
  const ratio = contrastRatio(brand.primaryColor, '#FFFFFF');
  console.log(`Primary color (${brand.primaryColor}) vs white contrast ratio: ${ratio.toFixed(2)}:1`);
  if (ratio < 4.5) {
    console.warn(
      `WARNING: White text on ${brand.primaryColor} has contrast ${ratio.toFixed(2)}:1 (below WCAG AA 4.5:1). Consider using a darker shade.`
    );
  }

  // Copy logo & icon assets to mobile/assets/
  fs.mkdirSync(assetsDir, { recursive: true });
  const copyMap = [
    ['logo.png', 'logo.png'],
    ['logo.png', 'icon.png'],
    ['logo.png', 'splash-icon.png'],
    ['app_icon_foreground.png', 'adaptive-icon.png'],
    ['app_icon_background.png', 'adaptive-icon-bg.png'],
  ];

  for (const [src, dest] of copyMap) {
    const srcPath = path.join(brandingDir, src);
    const destPath = path.join(assetsDir, dest);
    if (fs.existsSync(srcPath)) {
      fs.copyFileSync(srcPath, destPath);
    } else {
      console.warn(`WARNING: Missing branding file: ${src}`);
    }
  }

  // Generate mobile/src/config/brand.ts
  fs.mkdirSync(configDir, { recursive: true });
  const brandTs = `// AUTO-GENERATED by branding/apply_branding.js — DO NOT EDIT MANUALLY.
// Edit branding/brand.json and run "npm run apply-branding" to update.

export const BRAND = {
  appName: ${JSON.stringify(brand.appName)},
  slug: ${JSON.stringify(brand.slug || 'informed-diet')},
  primaryColor: ${JSON.stringify(brand.primaryColor)},
  primaryDarkColor: ${JSON.stringify(brand.primaryDarkColor)},
  accentColor: ${JSON.stringify(brand.accentColor)},
  splashBackgroundColor: ${JSON.stringify(brand.splashBackgroundColor || brand.primaryColor)},
  logoAsset: require('../../assets/logo.png'),
} as const;
`;
  fs.writeFileSync(path.join(configDir, 'brand.ts'), brandTs, 'utf-8');

  // Update mobile/app.json if present
  const appJsonPath = path.join(mobileDir, 'app.json');
  if (fs.existsSync(appJsonPath)) {
    const appJson = JSON.parse(fs.readFileSync(appJsonPath, 'utf-8'));
    appJson.expo = appJson.expo || {};
    appJson.expo.name = brand.appName;
    appJson.expo.slug = brand.slug || 'informed-diet';
    appJson.expo.icon = './assets/icon.png';
    appJson.expo.splash = {
      ...(appJson.expo.splash || {}),
      image: './assets/splash-icon.png',
      resizeMode: 'contain',
      backgroundColor: brand.splashBackgroundColor || brand.primaryColor,
    };
    appJson.expo.android = {
      ...(appJson.expo.android || {}),
      package: brand.androidPackage || 'com.informeddiet.app',
      adaptiveIcon: {
        foregroundImage: './assets/adaptive-icon.png',
        backgroundColor: brand.primaryColor,
      },
    };
    fs.writeFileSync(appJsonPath, JSON.stringify(appJson, null, 2) + '\n', 'utf-8');
  }

  console.log(`Branding applied successfully for "${brand.appName}"!`);
}

run();
